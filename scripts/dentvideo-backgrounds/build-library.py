#!/usr/bin/env python3
"""
Turns reviewed raw images into the shipped library.

    python3 -I scripts/dentvideo-backgrounds/build-library.py --raw <raw-dir> [--repo .]

  - approved = generated (results.json) minus review.v1.json "rejected"
  - JPEG 1080x1920 (centre crop of 1088 wide), progressive, quality searched
    down until the file is <= 90 KB (never below q=60; a soft, shallow-focus
    still life compresses well, so most land around 70-90 KB)
  - web/public/dentvideo/backgrounds/<id>.jpg  — single source of the pixels
    (served to the browser preview; the worker reads the same files locally
    in the monorepo or fetches them from dentvideo.com, see
    worker/src/dentvid/backgrounds/resolve.ts)
  - scripts/dentvideo-backgrounds/manifest.json — full record (prompt, seed, ...)
  - worker/src/dentvid/backgrounds/library.ts and
    web/src/lib/dentvid/backgrounds/library.ts — the identical, generated
    index the suggestion engine ranks (a test asserts they match)
"""
import argparse, io, json, os
from PIL import Image, ImageFilter

MAX_BYTES = 90 * 1024
W, H = 1080, 1920

def luminance_stats(im):
    g = im.convert("L").resize((108, 192))
    px = sorted(g.tobytes())
    mean = sum(px) / len(px) / 255
    p95 = px[int(len(px) * 0.95)] / 255
    return round(mean, 3), round(p95, 3)

def encode(im):
    # Most photos fit at q 64-88. Fine high-frequency texture (frost, sand
    # grain) does not; for those a barely visible softening (radius 0.8 px at
    # 1080 wide, under a 65-77 % tint in the video) beats blocky low-q JPEG.
    for soften in (0, 0.8, 1.4):
        src = im.filter(ImageFilter.GaussianBlur(soften)) if soften else im
        for q in range(88, 59, -2):
            buf = io.BytesIO()
            src.save(buf, "JPEG", quality=q, progressive=True, optimize=True, subsampling="4:2:0")
            if buf.tell() <= MAX_BYTES:
                return buf.getvalue(), q
    return buf.getvalue(), q

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", required=True)
    ap.add_argument("--repo", default=".")
    a = ap.parse_args()
    here = os.path.join(a.repo, "scripts/dentvideo-backgrounds")
    spec = json.load(open(os.path.join(here, "prompts.v1.json")))
    rejected = json.load(open(os.path.join(here, "review.v1.json")))["rejected"]
    results = json.load(open(os.path.join(a.raw, "results.json")))
    out_dir = os.path.join(a.repo, "web/public/dentvideo/backgrounds")
    os.makedirs(out_dir, exist_ok=True)

    manifest, total = [], 0
    for image_id in sorted(results):
        r = results[image_id]
        if image_id in rejected:
            continue
        src = Image.open(os.path.join(a.raw, f"{image_id}.jpg")).convert("RGB")
        if src.size[1] != 1920:
            continue  # wrong aspect never ships
        left = (src.size[0] - W) // 2
        im = src.crop((left, 0, left + W, H))
        data, q = encode(im)
        open(os.path.join(out_dir, f"{image_id}.jpg"), "wb").write(data)
        total += len(data)
        mean, p95 = luminance_stats(im)
        cat = spec["categories"][r["category"]]
        tags = sorted(set(cat["tags"]) | set(r.get("tags", [])))
        manifest.append({
            "id": image_id, "category": r["category"], "tags": tags, "subject": r["subject"],
            "prompt": r["prompt"], "seed": r["seed"], "model": spec["model"], "promptsVersion": spec["version"],
            "width": W, "height": H, "bytes": len(data), "quality": q,
            "luminance": mean, "luminanceP95": p95, "approved": True,
            "src": f"/dentvideo/backgrounds/{image_id}.jpg",
        })
    json.dump({"version": 1, "images": manifest}, open(os.path.join(here, "manifest.json"), "w"), indent=1, ensure_ascii=False)

    lines = [
        "// GENERATED by scripts/dentvideo-backgrounds/build-library.py — do not edit by hand.",
        "// Identical copies live in worker/src/dentvid/backgrounds/library.ts and",
        "// web/src/lib/dentvid/backgrounds/library.ts (a test keeps them in step).",
        "",
        "export type LibraryImage = { id: string; category: string; tags: string[]; luminance: number };",
        "",
        "export const BACKGROUND_LIBRARY: LibraryImage[] = [",
    ]
    for m in manifest:
        lines.append(f"  {{ id: {json.dumps(m['id'])}, category: {json.dumps(m['category'])}, tags: {json.dumps(m['tags'])}, luminance: {m['luminance']} }},")
    lines += ["];", ""]
    ts = "\n".join(lines)
    for p in ("worker/src/dentvid/backgrounds/library.ts", "web/src/lib/dentvid/backgrounds/library.ts"):
        os.makedirs(os.path.dirname(os.path.join(a.repo, p)), exist_ok=True)
        open(os.path.join(a.repo, p), "w").write(ts)
    cats = {}
    for m in manifest:
        cats[m["category"]] = cats.get(m["category"], 0) + 1
    print(f"approved {len(manifest)} images, {total / 1024 / 1024:.2f} MB, avg {total / max(1, len(manifest)) / 1024:.0f} KB; {cats}")

if __name__ == "__main__":
    main()
